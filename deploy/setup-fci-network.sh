#!/usr/bin/env bash
# Configure the dedicated FCI NIC of the NUC (static address, no DHCP, no
# gateway, MTU 1500, not managed by NetworkManager).
#
#   sudo bash deploy/setup-fci-network.sh            # values from /etc/robot-twin/robot-twin.env
#   sudo bash deploy/setup-fci-network.sh enp3s0 172.16.0.1/24
#
# It writes /etc/netplan/60-robot-fci.yaml (renderer networkd) and tells
# NetworkManager to leave the NIC alone, then runs `netplan apply`.
# It does not touch any other interface. It does not contact the robot.
set -euo pipefail
ENV_FILE=/etc/robot-twin/robot-twin.env
[ "$(id -u)" -eq 0 ] || { echo "run as root" >&2; exit 1; }
# shellcheck disable=SC1090
if [ -f "$ENV_FILE" ]; then set -a; . "$ENV_FILE"; set +a; fi
NIC="${1:-${FCI_NIC:-}}"
CIDR="${2:-${FCI_HOST_CIDR:-}}"
[ -n "$NIC" ] && [ "$NIC" != "enp0s0-CHANGE-ME" ] || { echo "set FCI_NIC (ip -br link) or pass it as argument 1" >&2; exit 2; }
[ -n "$CIDR" ] || { echo "set FCI_HOST_CIDR (e.g. 172.16.0.1/24) or pass it as argument 2" >&2; exit 2; }
ip link show "$NIC" >/dev/null 2>&1 || { echo "no interface $NIC; ip -br link:" >&2; ip -br link >&2; exit 2; }
if ip -4 route show default | grep -q " dev $NIC "; then
  echo "$NIC carries the default route: that is the LAN NIC, not the dedicated FCI NIC" >&2; exit 2
fi

cat > /etc/netplan/60-robot-fci.yaml <<YAML
# robot-twin: dedicated FCI link to the Panda control unit. Generated by
# deploy/setup-fci-network.sh. No DHCP, no gateway, no DNS: only the robot.
network:
  version: 2
  renderer: networkd
  ethernets:
    $NIC:
      dhcp4: false
      dhcp6: false
      link-local: []
      accept-ra: false
      addresses: [$CIDR]
      mtu: 1500
YAML
chmod 0600 /etc/netplan/60-robot-fci.yaml

if [ -d /etc/NetworkManager/conf.d ]; then
  cat > /etc/NetworkManager/conf.d/99-robot-fci-unmanaged.conf <<NM
[keyfile]
unmanaged-devices=interface-name:$NIC
NM
  systemctl reload NetworkManager 2>/dev/null || true
fi

netplan generate
netplan apply
sleep 2
ip -br addr show "$NIC"
echo "MTU: $(cat /sys/class/net/$NIC/mtu)"
if command -v nmcli >/dev/null 2>&1; then nmcli -t -f DEVICE,STATE device | grep "^$NIC:" || true; fi
